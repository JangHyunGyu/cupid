"""Generate an optional homepage subset; the complete licensed font stays intact.

Requires fonttools[woff] 4.66.1. Run from any directory with Python 3.
The CSS keeps the full font as a fallback for new copy and dynamic game text.
"""
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / 'assets/vendor/pretendard'
SOURCE = FONT_DIR / 'PretendardVariable.woff2'


def ranges(points):
    result = []
    start = end = None
    for point in sorted(points):
        if end is not None and point == end + 1:
            end = point
            continue
        if start is not None:
            result.append(f'U+{start:X}' + (f'-{end:X}' if end != start else ''))
        start = end = point
    if start is not None:
        result.append(f'U+{start:X}' + (f'-{end:X}' if end != start else ''))
    return ','.join(result)


def main():
    source_bytes = SOURCE.read_bytes()
    font = TTFont(SOURCE, recalcTimestamp=False)
    available = set(font.getBestCmap())
    # Full HTML includes settings, confirmation dialogs and localized labels.
    home_chars = set()
    for page in sorted(ROOT.glob('index*.html')):
        home_chars.update(map(ord, page.read_text(encoding='utf-8')))
    # Keep Latin, combining marks and punctuation together for text shaping.
    requested = home_chars | set(range(0x250)) | set(range(0x300, 0x370)) | set(range(0x1E00, 0x1F00)) | set(range(0x2000, 0x2070))
    points = available & requested
    options = subset.Options()
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.name_legacy = True
    options.glyph_names = True
    options.notdef_outline = True
    options.recalc_timestamp = False
    options.hinting = True
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points)
    worker.subset(font)
    # The derivative uses its own internal name under the source font's OFL RFN.
    # CSS aliases stay unchanged, so existing selectors and layout keep working.
    for record in font['name'].names:
        if record.nameID in {1, 3, 4, 6, 16, 21, 25}:
            replacement = 'CupidHomeSans' if record.nameID in {6, 25} else 'Cupid Home Sans'
            value = record.toUnicode().replace('Pretendard', replacement)
            record.string = value.encode(record.getEncoding())
    import io
    buffer = io.BytesIO()
    font.save(buffer)
    output_bytes = buffer.getvalue()
    digest = hashlib.sha256(output_bytes).hexdigest()[:12]
    filename = f'CupidHomeSans-{digest}.woff2'
    (FONT_DIR / filename).write_bytes(output_bytes)
    css = '/* Pretendard 1.3.9 | SIL OFL 1.1 | https://github.com/orioncactus/pretendard\n * Generated by scripts/build-home-font.py. Original font retained for all other text. */\n'
    for family in ['Pretendard', 'Pretendard Variable']:
        for source, unicode_range in [('PretendardVariable.woff2', ranges(available - points)), (filename, ranges(points))]:
            css += f"@font-face {{\n  font-family: '{family}';\n  font-weight: 45 920;\n  font-style: normal;\n  font-display: swap;\n  src: url('./{source}') format('woff2-variations');\n"
            if unicode_range:
                css += f'  unicode-range: {unicode_range};\n'
            css += '}\n\n'
    (FONT_DIR / 'pretendard-home.css').write_text(css.rstrip() + '\n', encoding='utf-8')
    manifest = {'source_sha256': hashlib.sha256(source_bytes).hexdigest(), 'source_bytes': len(source_bytes), 'subset_file': filename, 'subset_bytes': len(output_bytes), 'codepoints': sorted(points), 'fonttools_version': '4.66.1'}
    (ROOT / 'config/home-font.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    assert SOURCE.read_bytes() == source_bytes
    print(f'Homepage font: {len(source_bytes):,} -> {len(output_bytes):,} bytes; {len(points)} codepoints. Full fallback unchanged.')


if __name__ == '__main__':
    main()
