'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { listProtectedAssets, toLogicalAssetId } = require('./lib/cupid-protected-assets.cjs');
const { isEncryptedBuffer } = require('./lib/cupid-media-crypto.cjs');
const root = path.resolve(__dirname, '..');
const { resolveAssetSource, catalog } = require('./character-assets.cjs');
const { resolveMediaDelivery } = require('./lib/media-delivery.cjs');

function syncMediaManifest(write = false) {
  const storage = JSON.parse(fs.readFileSync(path.join(root, 'config/media-storage.json'), 'utf8'));
  const deliveryPath = path.join(root, 'config/media-delivery.json');
  const delivery = resolveMediaDelivery(storage, fs.existsSync(deliveryPath)
    ? JSON.parse(fs.readFileSync(deliveryPath, 'utf8')) : {});
  const entries = {};
  for (const relative of listProtectedAssets(root)) {
    const bytes = fs.readFileSync(resolveAssetSource(root, relative));
    if (!isEncryptedBuffer(bytes)) throw new Error(`Protected media must be encrypted: ${relative}`);
    const id = toLogicalAssetId(relative);
    const file = { path: relative, hash: createHash('sha256').update(bytes).digest('hex') };
    if (delivery[relative]?.sha256 !== storage[relative]?.sha256) file.deliveryHash = delivery[relative]?.sha256;
    (entries[id] ||= []).push(file);
  }
  const manifest = {};
  for (const [id, files] of Object.entries(entries)) {
    // Preserve existing content URLs and browser caches through the storage migration.
    const version = createHash('sha256').update(JSON.stringify(files)).digest('hex').slice(0, 24);
    manifest[id] = { version, files: files.map(file => {
      const item = delivery[file.path];
      if (!item || item.sourceHash !== file.hash || !/^[a-f0-9]{64}$/.test(item.sha256)
        || item.key !== 'images/' + item.sha256 + path.extname(file.path)
        || !/^[a-f0-9]{32}$/.test(item.etag) || !Number.isSafeInteger(item.size) || item.size <= 0) {
        throw new Error(`Upload and verify private media before building: ${file.path}`);
      }
      return { path: file.path, key: item.key, sha256: item.sha256, etag: item.etag, size: item.size };
    }) };
  }
  const versions = Object.fromEntries(Object.entries(manifest).map(([id, item]) => [id, item.version]));
  const aliases = {};
  for (const asset of catalog(root).data.assets) for (const file of Object.values(asset.files)) {
    aliases[file.source.replace(/\.(png|webp|jpg|jpeg)$/i, '')] = toLogicalAssetId(file.publicPaths[0]);
  }
  const gatePath = path.join(root, 'assets/js/media-gate.js');
  const gate = fs.readFileSync(gatePath, 'utf8');
  const marker = /\/\/ BEGIN GENERATED MEDIA VERSIONS[\s\S]*?\/\/ END GENERATED MEDIA VERSIONS/;
  if (!marker.test(gate)) throw new Error('Missing media version markers');
  const outputs = [
    [path.join(root, 'functions/_lib/character-asset-aliases.js'), '// Generated from config/character-assets.json. Historical grant IDs stay stable.\nexport const CHARACTER_ASSET_IDS = ' + JSON.stringify(aliases) + ';\n'],
    [path.join(root, 'functions/_lib/media-manifest.js'), '// Generated by scripts/sync-media-manifest.cjs. Private R2 object identities, never credentials.\nexport const MEDIA_MANIFEST = ' + JSON.stringify(manifest, null, 2) + ';\n'],
    [gatePath, gate.replace(marker, '// BEGIN GENERATED MEDIA VERSIONS\n  var MEDIA_VERSIONS = ' + JSON.stringify(versions) + ';\n  var CHARACTER_ASSET_IDS = ' + JSON.stringify(aliases) + ';\n  // END GENERATED MEDIA VERSIONS')]
  ];
  for (const [file, content] of outputs) {
    if (fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === content.replace(/\r\n/g, '\n')) continue;
    if (!write) throw new Error(`Media manifest is stale: ${path.relative(root, file)}`);
    fs.writeFileSync(file, content);
  }
  console.log(`[media] ${Object.keys(manifest).length} private R2 assets verified; content versions synchronized`);
  return manifest;
}

module.exports = { syncMediaManifest };
if (require.main === module) syncMediaManifest(process.argv.includes('--write'));
