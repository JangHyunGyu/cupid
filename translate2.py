def replace_texts_in_file(filepath, translations):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()

    count = 0
    for en_text, (es_text, ja_text) in translations.items():
        # Replace in es blocks
        pos = 0
        while True:
            idx = content.find('"es": {', pos)
            if idx == -1:
                break
            brace = 0
            end = idx + 6
            for k in range(idx + 6, len(content)):
                if content[k] == '{': brace += 1
                if content[k] == '}':
                    if brace == 0: end = k + 1; break
                    brace -= 1
            block = content[idx:end]
            target = '"text": "' + en_text + '"'
            if target in block:
                new_block = block.replace(target, '"text": "' + es_text + '"', 1)
                content = content[:idx] + new_block + content[end:]
                count += 1
            pos = idx + 7

        # Replace in ja blocks
        pos = 0
        while True:
            idx = content.find('"ja": {', pos)
            if idx == -1:
                break
            brace = 0
            end = idx + 6
            for k in range(idx + 6, len(content)):
                if content[k] == '{': brace += 1
                if content[k] == '}':
                    if brace == 0: end = k + 1; break
                    brace -= 1
            block = content[idx:end]
            target = '"text": "' + en_text + '"'
            if target in block:
                new_block = block.replace(target, '"text": "' + ja_text + '"', 1)
                content = content[:idx] + new_block + content[end:]
                count += 1
            pos = idx + 7

    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    return count

